// Reads the constants of SheenBidi (bidi types, general categories, scripts) and writes
//   src/unicode/enums.ts
// so that the values of the enumerations are the ones that the library returns.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const headers = resolve(process.env.SHEENBIDI_DIR ?? join(root, "build/deps/SheenBidi"), "Headers/SheenBidi");

/** `Left-to-Right Isolate` becomes `LeftToRightIsolate`, `Old_Italic` becomes `OldItalic`. */
function pascal(words) {
  return words
    .split(/[\s_\-]+/)
    .filter(Boolean)
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join("");
}

function members(file, prefix, label) {
  const text = readFileSync(join(headers, file), "utf8");
  const found = [];
  for (const match of text.matchAll(new RegExp(`${prefix}(\\w+)\\s*=\\s*(0x[0-9A-Fa-f]+),?\\s*/\\*\\*<\\s*(.*?)\\s*\\*/`, "g"))) {
    const comment = match[3];
    found.push({ name: pascal(label(comment)), value: match[2].toUpperCase().replace("0X", "0x") });
  }
  const names = new Set(found.map((member) => member.name));
  if (names.size !== found.length) throw new Error(`${file} has members with the same name.`);
  return found;
}

function enumeration(name, doc, list) {
  return `/** ${doc} */\nexport enum ${name} {\n${list.map((m) => `  ${m.name} = ${m.value},`).join("\n")}\n}\n`;
}

const afterColon = (comment) => comment.replace(/^[^:]*:\s*/, "");

